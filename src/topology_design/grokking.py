def train_run(cfg: RunConfig, verbose: bool = False) -> dict:
    torch.set_num_threads(1)
    model = build_model(cfg)
    tr, te = split(cfg.p, cfg.train_frac, cfg.data_seed)
    a, b, y = full_grid(cfg.p)
    atr, btr, ytr = a[tr], b[tr], y[tr]
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay, betas=(0.9, 0.98))
    traj: list[dict] = []
    t0 = time.time()
    grok_step = None
    diverged_at = None
    for step in range(cfg.steps + 1):
        opt.zero_grad(set_to_none=True)
        logits = model(atr, btr)
        loss = F.cross_entropy(logits, ytr)
        if not torch.isfinite(loss):
            diverged_at = step
            break
        loss.backward()
        if step % cfg.eval_every == 0:
            rec = {"step": step, **measure(model, tr, te, cfg.measure_paths), **grad_stats(model, loss, logits.detach(), ytr)}
            traj.append(rec)
            if verbose:
                print(f"{cfg.run_id} step {step} train {rec['train_acc']:.3f} test {rec['test_acc']:.3f} "
                      f"rule {rec['rule_frac']:.3f} excl_tr_acc {rec['excluded_train_acc']:.3f}", flush=True)
            if grok_step is None and rec["test_acc"] >= cfg.grok_thresh:
                grok_step = step
            if cfg.stop_after_grok and grok_step is not None and step - grok_step >= cfg.stop_after_grok:
                break
        opt.step()
    return {
        "config": asdict(cfg),
        "run_id": cfg.run_id,
        "n_params": n_params(model),
        "seconds": time.time() - t0,
        "trajectory": traj,
        "summary": {**summarize(traj, cfg), **stability_summary(traj, diverged_at)},
    }


def first_step(traj: list[dict], key: str, thresh: float) -> int | None:
    for r in traj:
        if r[key] >= thresh:
            return r["step"]
    return None


def summarize(traj: list[dict], cfg: RunConfig) -> dict:
    """Preregistered endpoints (see PREREGISTRATION.md)."""
    t_fit = first_step(traj, "train_acc", 0.99)
    t_grok = first_step(traj, "test_acc", cfg.grok_thresh)
    last = traj[-1]
    peak_mem = max(r["excluded_train_acc"] for r in traj)
    return {
        "t_fit": t_fit,
        "t_grok": t_grok,
        "grok_delay": (t_grok - t_fit) if (t_fit is not None and t_grok is not None) else None,
        "grokked": t_grok is not None,
        "final_train_acc": last["train_acc"],
        "final_test_acc": last["test_acc"],
        "final_rule_frac": last["rule_frac"],
        "peak_excluded_train_acc": peak_mem,  # how much memorization was ever present
        "final_ablate": last["ablate"],
        "final_branches": last["branches"],
        "steps_run": last["step"],
    }


def stability_summary(traj: list[dict], diverged_at: int | None) -> dict:
    """Study-2 endpoints: divergence, and collapse of training accuracy after the first fit (train acc >= 0.99)."""
    t_fit = first_step(traj, "train_acc", 0.99)
    if diverged_at is not None or t_fit is None:
        post_min = 0.0
    else:
        post_min = min(r["train_acc"] for r in traj if r["step"] >= t_fit)
    return {
        "diverged_at": diverged_at,
        "post_fit_min_train_acc": post_min,
        "stable": diverged_at is None and t_fit is not None and post_min >= 0.9,
    }


def save(result: dict, path: str) -> None:
    with open(path, "w") as f:
        json.dump(result, f)
