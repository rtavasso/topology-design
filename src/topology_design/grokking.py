"""Grokking testbed: modular addition with parameter-free routing variants.

Model (docs/SPEC.md, experiments/grokking/PREREGISTRATION.md):
    h_0   = E_a[a] + E_b[b]                         (learned embeddings, width d)
    h_i   = beta * h_{i-1} + alpha_i * F_i(h_{k_i})  F_i(h) = W2_i relu(W1_i h)
    logits = U h_L                                  (learned unembedding)

Every arm uses the same learned operators (same shapes, same parameter count). Arms differ only
in the parent vector k, the fixed per-branch multipliers alpha, and the fixed identity coefficient beta.

Because the readout is linear and branches write additively, the logits decompose EXACTLY into
per-branch *direct* contributions:  logits = beta^L U h_0 + sum_i beta^(L-i) alpha_i U F_i(h_{k_i}).
(With beta = 1 this is U h_0 + sum_i alpha_i U F_i.)  Total effects are measured separately by
ablation (setting alpha_i = 0 in the forward pass).
"""

from __future__ import annotations

import json
import math
import time
from dataclasses import asdict, dataclass, field

import torch
import torch.nn as nn
import torch.nn.functional as F

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

ARMS = {
    # name: (parents, alphas) for L = 3. Sink arms are generated by sink_arm().
    "seq": ((0, 1, 2), (1.0, 1.0, 1.0)),
    "par": ((0, 0, 0), (1.0, 1.0, 1.0)),
}


def sink_arm(s: float) -> tuple[tuple[int, ...], tuple[float, ...]]:
    """Blocks 1->2 form a chain; block 3 reads the embedding h_0 directly (the 'sink'), scaled by s."""
    return (0, 1, 0), (1.0, 1.0, float(s))


def arm_spec(arm: str) -> tuple[tuple[int, ...], tuple[float, ...]]:
    """'seq', 'par', 'sink_<s>', or 'pk<digits>' = explicit parent vector with unit multipliers (e.g. 'pk0102')."""
    if arm in ARMS:
        return ARMS[arm]
    if arm.startswith("sink_"):
        return sink_arm(float(arm[len("sink_") :]))
    if arm.startswith("pk") and arm[2:].isdigit():
        parents = tuple(int(c) for c in arm[2:])
        return parents, tuple(1.0 for _ in parents)
    raise ValueError(f"unknown arm {arm!r}")


def block_depths(parents) -> list[int]:
    """Composition depth of each block: d_i = 1 + d(parent), with the embedding h_0 at depth 0.
    (Parent k >= 1 refers to the accumulated state h_k, whose deepest contributor is max(d_1..d_k).)"""
    d: list[int] = []
    for k in parents:
        d.append(1 + (max(d[:k]) if k >= 1 else 0))
    return d


def longest_chain(parents) -> int:
    return max(block_depths(parents))


def root_readers(parents) -> int:
    """Number of blocks that read the raw embedding h_0 directly."""
    return sum(1 for k in parents if k == 0)


@dataclass
class RunConfig:
    arm: str = "seq"
    p: int = 97
    train_frac: float = 0.4
    d: int = 128
    hidden: int = 256
    beta: float = 1.0  # fixed identity coefficient (1 = standard residual)
    out_scale: float = 1.0  # fixed logit multiplier (richness knob)
    lr: float = 1e-3
    weight_decay: float = 1.0
    steps: int = 20000
    eval_every: int = 100
    model_seed: int = 0
    data_seed: int = 0
    init_scale: float = 1.0  # multiplies default init of every parameter
    stop_after_grok: int = 2000  # keep training this many steps after test acc >= grok_thresh (0 = never stop early)
    grok_thresh: float = 0.95
    measure_paths: bool = True  # record path_measure at each eval (Study 4); off for lr-selection runs
    tag: str = ""
    extra: dict = field(default_factory=dict)

    @property
    def run_id(self) -> str:
        wd = f"{self.weight_decay:g}"
        return f"{self.arm}_wd{wd}_lr{self.lr:g}_tf{self.train_frac:g}_os{self.out_scale:g}_b{self.beta:g}_m{self.model_seed}_d{self.data_seed}{('_' + self.tag) if self.tag else ''}"


