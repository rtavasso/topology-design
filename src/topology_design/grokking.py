# Data
# ---------------------------------------------------------------------------


def full_grid(p: int) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    a = torch.arange(p).repeat_interleave(p)
    b = torch.arange(p).repeat(p)
    return a, b, (a + b) % p


def split(p: int, train_frac: float, data_seed: int) -> tuple[torch.Tensor, torch.Tensor]:
    """Indices into the p*p grid (row-major over (a, b)); deterministic given data_seed."""
    g = torch.Generator().manual_seed(10_000 + data_seed)
    perm = torch.randperm(p * p, generator=g)
    n_train = int(round(train_frac * p * p))
    return perm[:n_train].sort().values, perm[n_train:].sort().values


# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------


class RoutedMLP(nn.Module):
    def __init__(self, p: int, d: int, hidden: int, parents, alphas, beta: float = 1.0, out_scale: float = 1.0):
        super().__init__()
        if len(parents) != len(alphas):
            raise ValueError("one alpha per block")
        for i, k in enumerate(parents, start=1):
            if not 0 <= k < i:
                raise ValueError(f"parent k_{i}={k} must satisfy 0 <= k < {i}")
        self.p, self.L = p, len(parents)
        self.parents = tuple(parents)
        self.register_buffer("alphas", torch.tensor(alphas, dtype=torch.float32))
        self.beta, self.out_scale = float(beta), float(out_scale)
        self.embed_a = nn.Embedding(p, d)
        self.embed_b = nn.Embedding(p, d)
        self.w1 = nn.ModuleList([nn.Linear(d, hidden, bias=False) for _ in parents])
        self.w2 = nn.ModuleList([nn.Linear(hidden, d, bias=False) for _ in parents])
        self.unembed = nn.Linear(d, p, bias=False)
        with torch.no_grad():  # embeddings at the same scale as Linear default fan-in init
            for e in (self.embed_a, self.embed_b):
                e.weight.normal_(0.0, 1.0 / math.sqrt(d))

    def block(self, i: int, h: torch.Tensor) -> torch.Tensor:
        return self.w2[i](F.relu(self.w1[i](h)))

    def forward(self, a, b, alphas: torch.Tensor | None = None, return_parts: bool = False, return_states: bool = False):
        alphas = self.alphas if alphas is None else alphas
        hs = [self.embed_a(a) + self.embed_b(b)]
        writes = []
        for i, k in enumerate(self.parents):
            w = alphas[i] * self.block(i, hs[k])
            writes.append(w)
            hs.append(self.beta * hs[-1] + w)
        logits = self.out_scale * self.unembed(hs[-1])
        if not return_parts:
            return (logits, hs) if return_states else logits
        # exact direct contributions: h_L = beta^L h_0 + sum_i beta^(L-i) w_i
        L = self.L
        parts = [self.out_scale * (self.beta**L) * self.unembed(hs[0])]
        parts += [self.out_scale * (self.beta ** (L - 1 - i)) * self.unembed(w) for i, w in enumerate(writes)]
        if return_states:
            return logits, torch.stack(parts), hs
        return logits, torch.stack(parts)  # (L+1, n, p): [embedding path, block 1, ..., block L]

    def branch_param_groups(self) -> dict[str, list[nn.Parameter]]:
        groups = {"embed": [self.embed_a.weight, self.embed_b.weight], "unembed": [self.unembed.weight]}
        for i in range(self.L):
            groups[f"block{i + 1}"] = [self.w1[i].weight, self.w2[i].weight]
        return groups


def build_model(cfg: RunConfig) -> RoutedMLP:
    parents, alphas = arm_spec(cfg.arm)
    torch.manual_seed(cfg.model_seed)  # identical initial weights across arms for the same seed
    model = RoutedMLP(cfg.p, cfg.d, cfg.hidden, parents, alphas, cfg.beta, cfg.out_scale)
    if cfg.init_scale != 1.0:
        with torch.no_grad():
            for prm in model.parameters():
                prm.mul_(cfg.init_scale)
    return model


def n_params(model: nn.Module) -> int:
    return sum(p.numel() for p in model.parameters())


